import { expect, test } from '@playwright/test'

test('M8 restores an actual offline run without claiming a live model benchmark', async ({ page }, testInfo) => {
  const runId = process.env.M8_EVALUATION_RUN_ID
  const password = process.env.E2E_PASSWORD
  test.skip(!runId || !password, 'Completed isolated evaluation run is required')
  await page.goto('/login')
  await page.getByLabel('邮箱').fill(process.env.E2E_EMAIL ?? 'owner@example.com')
  await page.getByLabel('密码').fill(password!)
  await page.getByRole('button', { name: '登录' }).click()
  await expect(page).toHaveURL(/\/app\/?$/)
  await page.goto(`/app/evaluations?run=${runId}`)
  await expect(page.getByRole('heading', { name: '评测中心' })).toBeVisible()
  await expect(page.getByText('未发布草案，仍需人工审阅', { exact: false })).toBeVisible()
  await expect(page.getByText(/结果不是 DeepSeek 实测准确率/)).toBeVisible()
  const detail = page.getByRole('region', { name: '评测运行详情' })
  await expect(detail.getByText('已完成', { exact: true })).toBeVisible()
  await expect(detail.locator('.evaluation-metrics').getByText('100.0%', { exact: true })).toHaveCount(3)
  const caseResults = detail.locator('.evaluation-table').last()
  await expect(caseResults.getByRole('row')).toHaveCount(10)
  const securityRequest = page.waitForResponse((response) => response.url().includes('/cases?') && response.url().includes('category=security'))
  await page.getByLabel('场景类别').selectOption('security')
  const securityPage = await securityRequest
  expect(await securityPage.json()).toMatchObject({ total: 2 })
  await expect(caseResults.getByRole('row')).toHaveCount(3)
  const failedRequest = page.waitForResponse((response) => response.url().includes('/cases?') && response.url().includes('status=failed'))
  await page.getByLabel('案例状态').selectOption('failed')
  const failedPage = await failedRequest
  expect(await failedPage.json()).toMatchObject({ total: 0 })
  await expect(caseResults.getByRole('row')).toHaveCount(1)
  await page.reload()
  await expect(detail.getByText('已完成', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(1)
  const checkbox = page.getByRole('checkbox')
  const start = page.getByRole('button', { name: '运行离线评测' })
  await expect(start).toBeDisabled()
  await checkbox.focus()
  await page.keyboard.press('Space')
  await expect(start).toBeEnabled()
  await page.screenshot({ path: testInfo.outputPath('m8-real-offline-evaluation.png'), fullPage: true })
})
